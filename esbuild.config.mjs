import { builtinModules } from "node:module"
import { readFileSync } from "node:fs"
import esbuild from "esbuild"
import process from "process"

const notices = readFileSync(new URL("./LICENSE", import.meta.url), "utf8").trim()
const banner =
	`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

${notices}
*/
`

const prod = (process.argv[2] === "production")

const options = {
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	minifyWhitespace: prod,
	minifySyntax: prod,
	minifyIdentifiers: prod,
	metafile: prod,
	treeShaking: true,
	outfile: "main.js",
}

if (prod) {
	const result = await esbuild.build(options)
	const bytes = result.metafile.outputs["main.js"].bytes
	if (bytes >= 5_000_000) throw new Error(`Plugin bundle exceeds the 5 MB budget (${bytes} bytes)`)
} else {
	const context = await esbuild.context(options)
	await context.watch()
}
